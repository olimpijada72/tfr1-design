#!/usr/bin/env python3
"""Render five annotated TfR1 views and save an interactive PyMOL session.

Usage: python3 -I scripts/visualize_target.py --open
Requires prepared data and a PyMOL executable; no Python packages in this interpreter.
"""
import argparse
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
SCENES = ("01_overview", "02_domains", "03_constraints", "04_target", "05_hotspots")


def resi(numbers):
    return "+".join(str(n) for n in numbers)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--open", action="store_true", help="Open the generated session in PyMOL")
    parser.add_argument("--pymol", default="pymol", help="PyMOL executable name or path")
    args = parser.parse_args()
    executable = shutil.which(args.pymol)
    if not executable:
        parser.error("PyMOL not found. Install PyMOL or pass --pymol /path/to/pymol.")
    raw = ROOT / "data/raw/1CX8.pdb"
    target = ROOT / "data/target/human_apical.pdb"
    inputs = {name: ROOT / f"data/target/{name}.json" for name in ("domains", "avoid_residues", "hotspots")}
    for path in (raw, target, *inputs.values()):
        if not path.is_file():
            parser.error(f"Missing {path}. Run python3 -I scripts/prep_target.py first.")
    domains, avoid, hotspots = (json.loads(p.read_text()) for p in inputs.values())
    chain = domains["chain"]
    (apical_start, apical_end), = domains["domains"]["apical"]
    patches = hotspots["patches"][:3]
    for patch in patches:
        if len(patch["human_positions"]) != 3 or patch["rfdiffusion_hotspot_res"] != [f"{chain}{n}" for n in patch["human_positions"]]:
            parser.error(f"Expected three-residue patches on chain {chain}; review target numbering.")
    # Domain spans become PyMOL residue ranges; the avoid list is split by what it touches.
    spans = {name: " or ".join(f"resi {a}-{b}" for a, b in v) for name, v in domains["domains"].items()}
    seam = [n for n, k in avoid["category"].items() if k == "seam"]
    tf_contact = [n for n, k in avoid["category"].items() if k in ("transferrin", "both")]
    out = ROOT / "data/visualization"
    out.mkdir(parents=True, exist_ok=True)
    driver = out / "render_target.py"
    driver.write_text(f'''# Generated by scripts/visualize_target.py; executed by PyMOL.
from pathlib import Path
from pymol import cmd

out = Path({str(out)!r})
patches = {[p["residues"] for p in patches]!r}
positions = {[p["human_positions"] for p in patches]!r}
cmd.reinitialize()
cmd.bg_color("white")
cmd.set("orthoscopic", 1)
cmd.set("ray_shadows", 0)
cmd.set("antialias", 2)
cmd.set("cartoon_fancy_helices", 1)
cmd.set("label_color", "black")
cmd.set("label_size", 20)
cmd.set("label_outline_color", "white")
cmd.set("stick_radius", 0.22)
cmd.set("sphere_scale", 0.3)
cmd.set("scene_buttons", 1)
cmd.viewport(1400, 1000)
for name, rgb in [("protease_grey", [0.62, 0.64, 0.66]),
                  ("apical_teal", [0.08, 0.55, 0.52]),
                  ("helical_slate", [0.36, 0.44, 0.62]),
                  ("partner_blue", [0.72, 0.78, 0.86]),
                  ("tf_orange", [0.93, 0.47, 0.10]),
                  ("seam_magenta", [0.78, 0.18, 0.52]),
                  ("glycan_yellow", [0.85, 0.72, 0.20]),
                  ("hotspot_gold", [0.94, 0.70, 0.08]),
                  ("hotspot_orange", [0.93, 0.33, 0.10]),
                  ("hotspot_pink", [0.75, 0.15, 0.48])]:
    cmd.set_color(name, rgb)

# 1CX8 biological assembly 2 is chains C/D with identity transforms. Keep the
# N-linked NAG sugars, which constrain binder access; drop the samarium ions,
# which are a crystallization additive rather than biology.
cmd.load({str(raw)!r}, "receptor")
cmd.remove("receptor and (not chain {chain}+D or resn SM or solvent)")
cmd.load({str(target)!r}, "apical_target")

both = "(receptor or apical_target) and chain {chain}"
cmd.select("protease_like", "receptor and chain {chain} and ({spans['protease_like']})")
cmd.select("apical_domain", "receptor and chain {chain} and ({spans['apical']})")
cmd.select("helical", "receptor and chain {chain} and ({spans['helical']})")
cmd.select("partner_chain", "receptor and chain D")
cmd.select("transferrin_site", "receptor and chain {chain} and resi {domains['transferrin_site'][0]}-{domains['transferrin_site'][1]}")
cmd.select("dimer_seam", both + " and resi {resi(seam) or 0}")
cmd.select("transferrin_contact", both + " and resi {resi(tf_contact) or 0}")
cmd.select("glycosites", "receptor and chain {chain} and resi {resi(domains['glycosylation_sites'])}")
cmd.select("glycans", "receptor and chain {chain} and resn NAG")
for i, group in enumerate(positions, 1):
    cmd.select(f"patch_{{i}}", both + " and resi " + "+".join(map(str, group)))

assert cmd.count_atoms("apical_target and name CA") == {apical_end - apical_start + 1}
assert set(cmd.get_chains("receptor")) == {{"{chain}", "D"}}
assert cmd.count_atoms("glycans") > 0, "expected resolved NAG on the receptor"

cmd.hide("everything", "all")
cmd.show("cartoon", "receptor or apical_target")
cmd.color("protease_grey", "protease_like")
cmd.color("apical_teal", "apical_domain or apical_target")
cmd.color("helical_slate", "helical")
cmd.color("partner_blue", "partner_chain")
cmd.set("cartoon_transparency", 0.55, "partner_chain")
# The transferrin site is 52 residues; as cartoon colour it reads, as sticks it is a blob.
cmd.color("tf_orange", "transferrin_site or transferrin_contact")
cmd.show("sticks", "dimer_seam or transferrin_contact")
cmd.color("seam_magenta", "dimer_seam")
cmd.show("sticks", "glycans")
cmd.show("spheres", "glycans")
cmd.color("glycan_yellow", "glycans or glycosites")

colors = ["hotspot_gold", "hotspot_orange", "hotspot_pink"]
offsets = [(3, 3, 0), (5, -3, 0), (-6, 1, 0)]


def draw_patch(index, labelled):
    """Colour one candidate triplet; label it only where labels will not collide."""
    for n, name, color, offset in zip(positions[index], patches[index], colors, offsets):
        selection = f"{{both}} and resi {{n}}"
        assert cmd.count_atoms(selection + " and name CA") == 2, f"expected {{n}} once per object"
        cmd.show("sticks", selection)
        cmd.color(color, selection)
        if labelled:
            # One label per residue, anchored on its backbone C-alpha atom.
            cmd.label(selection + " and name CA", repr(name))
            cmd.set("label_position", offset, selection + " and name CA")


# Scenes 01-04 carry the primary patch only; all three are drawn in the close-up.
draw_patch(0, labelled=True)
cmd.label("receptor and chain {chain} and name CA and resi {domains['termini'][0]}", '"N"')
cmd.label("receptor and chain {chain} and name CA and resi {domains['termini'][1]}", '"C"')

def capture(name, message):
    cmd.deselect()
    cmd.scene(name, "store", message=message)
    cmd.png(str(out / (name + ".png")), width=1400, height=1000, dpi=150, ray=1)

# 01 - the whole ectodomain dimer, coloured by domain. The isolated target shares
# these coordinates, so exactly one of the two objects is enabled in every scene.
cmd.disable("apical_target")
cmd.orient("receptor")
cmd.zoom("receptor", buffer=8, complete=1)
capture("01_overview",
        "TfR1 ectodomain dimer, 1CX8 assembly 2. Chain {chain}: protease-like grey, "
        "apical teal, helical slate. Partner chain D translucent blue. "
        "Yellow = N-linked sugars. No membrane or intracellular tail is resolved.")

# 02 - one chain, domain architecture and the transferrin docking site.
cmd.hide("everything", "partner_chain")
cmd.orient("receptor and chain {chain}")
cmd.zoom("receptor and chain {chain}", buffer=6, complete=1)
capture("02_domains",
        "Chain {chain} alone, N and C termini labelled. Orange = transferrin docking "
        "site {domains['transferrin_site'][0]}-{domains['transferrin_site'][1]} on the helical domain: blocking it stops iron delivery "
        "body-wide. The teal apical domain is the design target.")

# 03 - everything on the apical domain a binder must respect.
cmd.show("cartoon", "partner_chain")
cmd.orient("receptor")
cmd.zoom("apical_domain", buffer=14, complete=1)
capture("03_constraints",
        "Apical domain in receptor context. Magenta = buried against the partner "
        "subunit in the biological assembly. Yellow = glycosylation sites and "
        "resolved sugars. Gold/orange/pink = candidate anchors. Avoid magenta and yellow.")

# 04 - the isolated file handed to the generator.
cmd.disable("receptor")
cmd.enable("apical_target")
cmd.orient("apical_target")
cmd.zoom("apical_target", buffer=5, complete=1)
capture("04_target",
        "human_apical.pdb exactly as the generator receives it: residues "
        "{apical_start}-{apical_end} of chain {chain}, {apical_end - apical_start + 1} amino acids, original numbering. "
        "Space that looks open here may be occupied in the intact receptor.")

# 05 - close-up of the candidate patches, all three drawn and labelled.
for index in range(1, len(positions)):
    draw_patch(index, labelled=True)
hotspot_selection = "apical_target and (" + " or ".join(f"patch_{{i}}" for i in range(1, len(positions) + 1)) + ")"
cmd.show("spheres", hotspot_selection)
cmd.orient("apical_target")
cmd.zoom(hotspot_selection, buffer=7, complete=1)
capture("05_hotspots",
        "Candidate attachment patches, best first: {' | '.join(', '.join(p['residues']) for p in patches)}. "
        "Provisional structure-derived anchors, not measured hotspots. They are not "
        "histidines; histidines go on the designed binder later.")

cmd.enable("receptor")
cmd.scene("01_overview", "recall", animate=0)
cmd.save(str(out / "tfr1.pse"))
print("TFR1_VISUALIZATION_COMPLETE", flush=True)
cmd.quit()
''')
    result = subprocess.run([executable, "-cq", str(driver)], capture_output=True, text=True)
    (out / "render.log").write_text(result.stdout + result.stderr)
    outputs = [out / f"{name}.png" for name in SCENES] + [out / "tfr1.pse"]
    if result.returncode or "TFR1_VISUALIZATION_COMPLETE" not in result.stdout or not all(p.is_file() and p.stat().st_size for p in outputs):
        print(f"Rendering failed; inspect {out / 'render.log'}", file=sys.stderr)
        return 1
    for path in outputs:
        print(path)
    print(f"\nchain {chain}: " + ", ".join(f"{k.replace('_', '-')} {v}" for k, v in domains["domains"].items()))
    print(f"transferrin site {domains['transferrin_site'][0]}-{domains['transferrin_site'][1]}, "
          f"glycosylation at {resi(domains['glycosylation_sites'])}")
    print(f"avoid on the apical domain: {len(avoid['category'])} residues "
          f"({len(seam)} against the partner subunit, {len(tf_contact)} against transferrin)")
    for i, patch in enumerate(patches, 1):
        print(f"candidate patch {i}: {', '.join(patch['residues'])}  "
              f"(mouse {', '.join(map(str, patch['mouse_positions']))})")
    if args.open:
        with (out / "viewer.log").open("w") as log:
            subprocess.Popen([executable, str(out / "tfr1.pse")], stdin=subprocess.DEVNULL,
                             stdout=log, stderr=log, start_new_session=True)
        print("\nOpened PyMOL. Scenes: " + ", ".join(SCENES) + ".")
    return 0


if __name__ == "__main__":
    sys.exit(main())
